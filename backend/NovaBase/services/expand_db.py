def upsert_org(db, org_map, slug, name, org_type, country, url):
    if slug in org_map:
        return org_map[slug]
    existing = db.query(Organization).filter_by(slug=slug).first()
    if existing:
        org_map[slug] = existing
        return existing
    o = Organization(name=name, slug=slug, organization_type=org_type,
                     country=country, official_url=url)
    db.add(o); db.flush()
    org_map[slug] = o
    return o


def upsert_mission(db, mm, slug, name, dest, launch, end, status, desc, url):
    if slug in mm:
        return mm[slug]
    existing = db.query(Mission).filter_by(slug=slug).first()
    if existing:
        mm[slug] = existing
        return existing
    m = Mission(slug=slug, name=name, destination_category=dest,
                launch_date=launch, mission_end_date=end,
                mission_status=status, description=desc, official_url=url)
    db.add(m); db.flush()
    mm[slug] = m
    return m


def insert_hw(db, org_map, mm, seen, seen_names, h):
    if h["slug"] in seen or h["name"] in seen_names:
        print(f"  SKIP (already present): {h['slug']}")
        return False
    mission = mm.get(h["mission_slug"])
    if not mission:
        print(f"  SKIP (no mission): {h['slug']}")
        return False

    def oid(key):
        s = h.get(key)
        return org_map[s].id if s and s in org_map else None

    hw = Hardware(
        name=h["name"], slug=h["slug"], mission_id=mission.id,
        manufacturer_id=oid("manufacturer_slug"),
        operator_id=oid("operator_slug"),
        mission_agency_id=oid("mission_agency_slug"),
        object_type=h["object_type"], destination=h["destination"],
        operational_status=h["operational_status"],
        physical_status=h.get("physical_status"),
        launch_date=h.get("launch_date"), landing_date=h.get("landing_date"),
        decommission_date=h.get("decommission_date"),
        location_description=h.get("location_description"),
        latitude=h.get("latitude"), longitude=h.get("longitude"),
        short_description=h["short_description"],
        educational_description=h["educational_description"],
        how_it_works=h["how_it_works"],
        why_it_is_important=h["why_it_is_important"],
        scientific_purpose=h["scientific_purpose"],
        current_or_last_known_status=h["current_or_last_known_status"],
        hardware_materials=h.get("hardware_materials"),
        official_url=h["official_url"],
        verification_status=h.get("verification_status", "Verified from official records"),
        last_verified_at=h.get("last_verified_at"),
    )
    db.add(hw); db.flush()
    seen.add(h["slug"])
    seen_names.add(h["name"])

    for a in h.get("aliases", []):
        db.add(HardwareAlias(hardware_id=hw.id,
                             alias=a["alias"], alias_type=a["alias_type"]))
    for kw in h.get("keywords", []):
        db.add(HardwareKeyword(hardware_id=hw.id, keyword=kw.lower()))
    for img in h.get("images", []):
        db.add(HardwareImage(
            hardware_id=hw.id,
            item_type=img.get("item_type", "Photo"),
            title=img["title"], description=img.get("description"),
            image_url=img["image_url"], source_url=img["source_url"],
            attribution=img["attribution"],
            publication_date=img.get("publication_date")))
    for src in h.get("sources", []):
        db.add(HardwareSource(
            hardware_id=hw.id,
            source_name=src["source_name"], source_url=src["source_url"],
            source_type=src["source_type"],
            evidence_notes=src.get("evidence_notes"),
            last_checked_at=src.get("last_checked_at")))
    return True


